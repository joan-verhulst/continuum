/*
 * The site's own theme, ContinuumUI, as a scoped block: the values of the app.css the theme builder
 * exported (brand/continuum-ui/app.css) under `.continuum[data-theme="continuum-ui"]`, light and
 * dark. The site's frame opens that theme; the previews and screens open Continuum's default inside
 * it, so the docs show the values they state. Runs before dev and build; the output is not tracked.
 */
import { mkdir, readFile, writeFile } from 'node:fs/promises';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const source = join(here, '../../brand/continuum-ui/app.css');
const target = join(here, '../src/styles/continuum-ui.css');
const name = 'continuum-ui';

const css = (await readFile(source, 'utf8')).replace(/\/\*[\s\S]*?\*\//g, '');

/** The custom properties of the first block whose head matches. */
const block = head => {
    const start = css.search(head);
    if (start < 0) return [];
    const open = css.indexOf('{', start);
    let depth = 0;
    let end = open;
    for (let i = open; i < css.length; i++) {
        if (css[i] === '{') depth++;
        if (css[i] === '}' && --depth === 0) {
            end = i;
            break;
        }
    }
    return css
        .slice(open + 1, end)
        .split(';')
        .map(part => part.trim())
        .filter(part => part.startsWith('--'));
};

// The look a theme changes; type sizes, spacing and widths stay the system's (the export repeats them).
const themed =
    /^--(color|radius|shadow|font-sans|action-gradient|nav-active-image|avatar|chart-texture)/;
const keep = declarations => declarations.filter(declaration => themed.test(declaration));

const light = keep([...block(/@theme\b[^{]*\{/), ...block(/:root\s*\{/)]);
const dark = keep(block(/\[data-mode="dark"\]\s*\{/));

const lines = list => list.map(declaration => `    ${declaration};`).join('\n');
const out = `/* Generated by web/scripts/scope-theme.mjs from brand/continuum-ui/app.css. Do not edit. */
.continuum[data-theme="${name}"] {
${lines(light)}
}

.continuum[data-theme="${name}"][data-mode="dark"] {
    color-scheme: dark;
${lines(dark)}
}
`;

await mkdir(dirname(target), { recursive: true });
await writeFile(target, out);
console.log(`Scoped ${light.length} light and ${dark.length} dark values as ${name}`);
